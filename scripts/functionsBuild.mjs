// Shared esbuild options for the Edge Function `career-ops`: used by scripts/build-functions.mjs and
// by the test that checks the deployed bundle is up to date.
import { readFile } from 'node:fs/promises'
import path from 'node:path'

/**
 * Vite's `?raw` imports (the CSV tables in src/data) as text. Paths stay relative so the bundle is
 * the same on every machine.
 */
const rawText = {
  name: 'raw-text',
  setup(build) {
    build.onResolve({ filter: /\?raw$/ }, (args) => ({
      path: path.relative(process.cwd(), path.resolve(args.resolveDir, args.path.replace(/\?raw$/, ''))),
      namespace: 'raw',
    }))
    build.onLoad({ filter: /.*/, namespace: 'raw' }, async (args) => ({
      contents: await readFile(path.resolve(process.cwd(), args.path), 'utf8'),
      loader: 'text',
    }))
  },
}

export const functionsBuildOptions = {
  entryPoints: ['src/server/edge/careerOpsFunction.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'none',
  banner: { js: '// Generated by `npm run build:functions` from src/server. Do not edit.' },
  plugins: [rawText],
}
